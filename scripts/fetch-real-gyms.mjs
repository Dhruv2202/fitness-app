// One-off script: pulls real gyms/spas/yoga studios/activity centres in
// Delhi from OpenStreetMap (free, no API key) and writes them to
// src/data/realPlaces.js. Re-run this any time to refresh the snapshot.

import { writeFile } from "node:fs/promises";

// Rough bounding box covering Delhi NCT: south,west,north,east
const BBOX = "28.40,76.83,28.88,77.35";

const query = `
[out:json][timeout:25];
(
  node["leisure"="fitness_centre"](${BBOX});
  way["leisure"="fitness_centre"](${BBOX});
  node["amenity"="gym"](${BBOX});
  node["leisure"="sports_centre"](${BBOX});
  way["leisure"="sports_centre"](${BBOX});
  node["sport"="yoga"](${BBOX});
  node["amenity"="spa"](${BBOX});
  node["leisure"="spa"](${BBOX});
);
out center tags;
`;

function typeFor(tags) {
  if (tags.sport === "yoga") return "Yoga Studio";
  if (tags.amenity === "spa" || tags.leisure === "spa") return "Spa";
  if (tags.leisure === "fitness_centre" || tags.amenity === "gym")
    return "Gym";
  return "Activity Centre";
}

function iconFor(type) {
  return { Gym: "🏋️", Spa: "💆", "Yoga Studio": "🧘", "Activity Centre": "⚽" }[
    type
  ];
}

function addressFor(tags) {
  const parts = [
    tags["addr:housenumber"],
    tags["addr:street"],
    tags["addr:suburb"] || tags["addr:city"],
    tags["addr:postcode"],
  ].filter(Boolean);
  return parts.length ? parts.join(", ") : null;
}

const res = await fetch("https://overpass-api.de/api/interpreter", {
  method: "POST",
  headers: {
    "Content-Type": "application/x-www-form-urlencoded",
    Accept: "application/json",
    "User-Agent": "fitness-app-delhi/1.0 (learning project)",
  },
  body: `data=${encodeURIComponent(query)}`,
});

if (!res.ok) {
  const body = await res.text();
  throw new Error(`Overpass API returned ${res.status}: ${body.slice(0, 500)}`);
}

const json = await res.json();

const seen = new Set();
const places = [];

for (const el of json.elements) {
  const tags = el.tags || {};
  if (!tags.name) continue;
  if (seen.has(tags.name)) continue;
  seen.add(tags.name);

  const type = typeFor(tags);
  places.push({
    id: places.length + 1,
    name: tags.name,
    type,
    area: tags["addr:suburb"] || tags["addr:city"] || "Delhi",
    address: addressFor(tags),
    fee: null,
    rating: null,
    icon: iconFor(type),
    phone: tags.phone || tags["contact:phone"] || null,
    timings: tags.opening_hours || null,
    amenities: [
      tags.wheelchair === "yes" ? "Wheelchair accessible" : null,
      tags.internet_access ? "Free WiFi" : null,
      tags.air_conditioning === "yes" ? "AC" : null,
    ].filter(Boolean),
  });
}

places.sort((a, b) => a.name.localeCompare(b.name));

const output = `// Auto-generated by scripts/fetch-real-gyms.mjs from OpenStreetMap data.
// Re-run that script to refresh. Fields OSM doesn't have (fee, rating) are null.

export const realPlaces = ${JSON.stringify(places, null, 2)};
`;

await writeFile(
  new URL("../src/data/realPlaces.js", import.meta.url),
  output
);

console.log(`Wrote ${places.length} real places to src/data/realPlaces.js`);
