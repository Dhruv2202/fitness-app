-- ---------------------------------------------------------------------------
-- Who is allowed to manage content
-- ---------------------------------------------------------------------------
create table if not exists admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table admins enable row level security;

-- Must not query `admins` here, or the policy recurses into itself.
drop policy if exists "You can see your own admin row" on admins;
create policy "You can see your own admin row"
  on admins for select
  using (user_id = auth.uid());

-- Makes you an admin. Change the email if you signed up with a different one.
