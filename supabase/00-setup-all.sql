-- ---------------------------------------------------------------------------
-- Shop click tracking
-- ---------------------------------------------------------------------------
create table if not exists product_clicks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  product_id integer not null,
  clicked_at timestamptz not null default now()
);

alter table product_clicks enable row level security;

drop policy if exists "Users can view their own clicks" on product_clicks;
create policy "Users can view their own clicks"
  on product_clicks for select using (auth.uid() = user_id);

drop policy if exists "Anyone can record a click" on product_clicks;
create policy "Anyone can record a click"
  on product_clicks for insert
  with check (user_id is null or auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- Photo storage
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('photos', 'photos', true)
on conflict (id) do nothing;

drop policy if exists "Anyone can view photos" on storage.objects;
create policy "Anyone can view photos"
  on storage.objects for select
  using (bucket_id = 'photos');

drop policy if exists "Admins can upload photos" on storage.objects;
create policy "Admins can upload photos"
  on storage.objects for insert
  with check (
    bucket_id = 'photos'
    and exists (select 1 from admins where user_id = auth.uid())
  );

drop policy if exists "Admins can replace photos" on storage.objects;
create policy "Admins can replace photos"
  on storage.objects for update
  using (
    bucket_id = 'photos'
    and exists (select 1 from admins where user_id = auth.uid())
  );

drop policy if exists "Admins can delete photos" on storage.objects;
create policy "Admins can delete photos"
  on storage.objects for delete
  using (
    bucket_id = 'photos'
    and exists (select 1 from admins where user_id = auth.uid())
  );
