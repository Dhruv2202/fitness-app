on conflict (user_id) do nothing;

-- ---------------------------------------------------------------------------
-- Places
-- ---------------------------------------------------------------------------
create table if not exists places (
  id bigint primary key generated by default as identity,
  osm_id bigint unique,
  name text not null,
  type text not null,
  area text,
  address text,
  lat double precision,
  lon double precision,
  fee text,
  rating numeric(2,1),
  phone text,
  timings text,
  amenities text[] not null default '{}',
  photo_url text,
  created_at timestamptz not null default now()
);

alter table places enable row level security;

drop policy if exists "Anyone can view places" on places;
create policy "Anyone can view places"
  on places for select using (true);

drop policy if exists "Admins can add places" on places;
create policy "Admins can add places"
  on places for insert
  with check (exists (select 1 from admins where user_id = auth.uid()));

drop policy if exists "Admins can edit places" on places;
create policy "Admins can edit places"
  on places for update
  using (exists (select 1 from admins where user_id = auth.uid()));

drop policy if exists "Admins can delete places" on places;
create policy "Admins can delete places"
  on places for delete
  using (exists (select 1 from admins where user_id = auth.uid()));

